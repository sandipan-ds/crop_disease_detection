"""
Custom PyTorch Dataset for crop disease detection.

Loads images from local filesystem using CSV manifests
(train.csv / test.csv) generated by the notebook.
"""

import pandas as pd
from pathlib import Path
from PIL import Image
from torch.utils.data import Dataset
from torchvision.transforms.functional import to_tensor


class CropDiseaseDataset(Dataset):
    """
    Loads crop disease images from a CSV manifest.

    Expected CSV columns:
        - image_path:  relative path from project root (e.g., data/processed/combined_train/Apple_Apple_Scab/...)
        - label:       integer class label (0-101)
        - target:      string class name (for display only)

    Args:
        csv_path:      path to train.csv or test.csv
        data_root:     root directory that image_path is relative to
        sample_n:      if set, randomly sample N rows (for local testing)
    """

    def __init__(self, csv_path, data_root, sample_n=None):
        self.data_root = Path(data_root)

        # Load CSV
        self.df = pd.read_csv(csv_path)
        self.df.columns = self.df.columns.str.strip()

        if "label" in self.df.columns and pd.api.types.is_integer_dtype(self.df["label"]):
            pass
        else:
            from sklearn.preprocessing import LabelEncoder
            le = LabelEncoder()
            self.df["label"] = le.fit_transform(self.df["target"])

        # Optional: subsample for local testing (stratified by class)
        if sample_n is not None and sample_n < len(self.df):
            per_class = max(1, sample_n // self.df["label"].nunique())
            sampled = []
            for label_val in self.df["label"].unique():
                class_df = self.df[self.df["label"] == label_val]
                n = min(len(class_df), per_class)
                sampled.append(class_df.sample(n=n, random_state=42))
            self.df = pd.concat(sampled, ignore_index=True)

        self.image_paths = [p.replace("\\", "/") for p in self.df["image_path"].values]
        self.labels = self.df["label"].values
        self.class_names = self.df["target"].values
        self.num_classes = self.df["label"].nunique()

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        # Build full path (forward slashes ensure Linux compatibility)
        img_path = self.data_root / self.image_paths[idx]
        label = self.labels[idx]

        # Load image → fixed-size float32 tensor (GPU transforms applied later)
        image = Image.open(img_path).convert("RGB")
        image = image.resize((256, 256), Image.BILINEAR)
        image = to_tensor(image)

        return image, label

    def get_labels(self):
        """Return all labels (used by StratifiedKFold)."""
        return self.labels.tolist()

    def get_class_names(self):
        """Return sorted unique class names."""
        return sorted(self.df["target"].unique().tolist())
